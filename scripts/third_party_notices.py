#!/usr/bin/env python3
"""Generate THIRD_PARTY_NOTICES.md from real installed data: web/package-lock.json + node_modules licence fields,
the vendored anatomy kit, and the Python packages pinned in requirements-api.txt (importlib.metadata).

  .\\.venv\\Scripts\\python.exe scripts/third_party_notices.py
"""

from __future__ import annotations

import json
import re
import sys
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ACCEPTED = {"MIT", "Apache-2.0", "Apache Software License", "BSD License", "BSD-2-Clause", "BSD-3-Clause", "ISC", "OFL-1.1", "0BSD", "BlueOak-1.0.0", "CC0-1.0", "Python-2.0"}


def npm_rows() -> list[tuple[str, str, str, bool]]:
    lock = json.loads((ROOT / "web" / "package-lock.json").read_text(encoding="utf-8"))
    rows = []
    for path, info in lock.get("packages", {}).items():
        if not path.startswith("node_modules/"):
            continue
        name = path.split("node_modules/")[-1]
        lic = info.get("license") or ""
        if not lic:
            pj = ROOT / "web" / path / "package.json"
            if pj.is_file():
                lic = json.loads(pj.read_text(encoding="utf-8")).get("license", "") or "UNKNOWN"
        rows.append((name, info.get("version", "?"), lic if isinstance(lic, str) else str(lic), bool(info.get("dev"))))
    return sorted(set(rows))


def py_rows() -> list[tuple[str, str, str]]:
    out = []
    for line in (ROOT / "requirements-api.txt").read_text(encoding="utf-8").splitlines():
        m = re.match(r"^([A-Za-z0-9_.\-]+)==", line.strip())
        if not m:
            continue
        md = metadata.metadata(m.group(1))
        lic = md.get("License-Expression") or ""
        if not lic:
            classifiers = [c.split(" :: ")[-1] for c in md.get_all("Classifier") or [] if c.startswith("License ::")]
            lic = "; ".join(classifiers) or (md.get("License") or "UNKNOWN").splitlines()[0][:40]
        out.append((m.group(1), metadata.version(m.group(1)), lic))
    return out


def main() -> int:
    npm, py = npm_rows(), py_rows()
    flag = lambda lic: "" if any(a in lic for a in ACCEPTED) else " ⚠ review"
    prod = [r for r in npm if not r[3]]
    dev = [r for r in npm if r[3]]
    lines = [
        "# Third-party notices (CryptoShift web app v2)",
        "",
        "Generated by `scripts/third_party_notices.py` from `web/package-lock.json`, the installed `node_modules` licence",
        "fields and installed Python package metadata. Accepted licences: MIT, Apache-2.0, BSD, ISC, OFL (owner rule);",
        "anything else is marked ⚠ review.",
        "",
        "## Vendored source",
        "",
        "| Component | Version | Licence | Where |",
        "|---|---|---|---|",
        "| anatomy kit (wheresryan22/anatomy) | commit 1482e84 | MIT | `web/src/components/iso/` (licence text: `LICENSE-anatomy-MIT.txt`) |",
        "",
        f"## npm packages shipped in the app bundle ({len(prod)})",
        "",
        "| Package | Version | Licence |",
        "|---|---|---|",
        *[f"| {n} | {v} | {lic}{flag(lic)} |" for n, v, lic, _ in prod],
        "",
        f"## npm development and test tools, not shipped ({len(dev)})",
        "",
        "axe-core and @axe-core/playwright are MPL-2.0: allowed by the owner as dev-only test tools (never bundled).",
        "lightningcss (MPL-2.0, Tailwind's CSS compiler) and caniuse-lite (CC-BY-4.0, browser data) run only at build time and are",
        "not in the bundle; they are outside the accepted list and are flagged for an OWNER DECISION (keep as dev-only, or replace).",
        "",
        "| Package | Version | Licence |",
        "|---|---|---|",
        *[f"| {n} | {v} | {lic}{'' if 'MPL' in lic and 'axe' in n else flag(lic)} |" for n, v, lic, _ in dev],
        "",
        f"## Python packages added for the backend (`requirements-api.txt`, {len(py)})",
        "",
        "| Package | Version | Licence |",
        "|---|---|---|",
        *[f"| {n} | {v} | {lic}{flag(lic)} |" for n, v, lic in py],
        "",
    ]
    (ROOT / "THIRD_PARTY_NOTICES.md").write_text("\n".join(lines), encoding="utf-8")
    review = [l for l in lines if "⚠ review" in l]
    print(f"npm shipped {len(prod)}, npm dev {len(dev)}, python {len(py)}; flagged for review: {len(review)}")
    for r in review[:20]:
        print("  ", r)
    return 0


if __name__ == "__main__":
    sys.exit(main())
